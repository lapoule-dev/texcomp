//! KTX 2.0 files: one texture (2D, 3D, array, cubemap or cubemap array) in
//! a block-compressed or RGBA8 format, with its mips, read and written.
//!
//! The Khronos container lets pre-compressed imagery be stored and served as
//! files (`image/ktx2`), for instance as the tiles of an archive: a tile cut
//! out of it opens in any KTX 2.0 tool.
//!
//! Written from the Khronos *KTX File Format Specification*, version 2.0
//! (<https://registry.khronos.org/KTX/specs/2.0/ktxspec.v2.html>), and the
//! *Khronos Data Format Specification* 1.4 for the descriptor
//! (<https://registry.khronos.org/DataFormat/specs/1.4/dataformat.1.4.html>).
//! Section numbers in the comments are those documents'.
//!
//! What is supported, both ways, completely:
//!
//! - **Formats** ([`Format`]): UASTC LDR 4×4 (`vkFormat` UNDEFINED with a
//!   UASTC descriptor, each of its five channel ids), BC7, ASTC 4×4 and
//!   RGBA8, linear or sRGB; the descriptor of each written and checked
//!   sample by sample, premultiplied alpha included.
//! - **Texture types** (§4.1): 1D (RGBA8 only: a block format has a height),
//!   2D, 3D, arrays of 1D and 2D, cubemaps and cubemap arrays; any number of
//!   mips from 1 to the full chain, or `levelCount` 0 (RGBA8: one level,
//!   the rest to be generated by the loader, [`Texture::generate_mips`]).
//! - **Supercompression** (§3.8): none, Zstandard (scheme 2) and ZLIB
//!   (scheme 3), level by level ([`Supercompression`]).
//! - **Key/value data** (§3.11): `KTXorientation` (checked: a file whose
//!   texels do not start at the top left is refused, since read as stored
//!   its image would come out flipped), `KTXwriter` (always written, as
//!   `texcomp <version>`), and every other pair kept as it is
//!   ([`Texture::key_values`]).
//!
//! What is refused, with a [`Ktx2Error`] that says so: every other
//! `vkFormat` ([`Ktx2Error::VkFormat`]), ETC1S and its BasisLZ
//! supercompression ([`Ktx2Error::Unsupported`],
//! [`Ktx2Error::Supercompression`]), 3D arrays (which KTX 2.0 does not
//! define), and anything that breaks a rule of the specification.
//!
//! [`read`] validates every size and offset against the file and never
//! panics, whatever the bytes.

use crate::BlockFormat;

/// The media type of a KTX 2.0 file (KTX 2.0 §7).
pub const MEDIA_TYPE: &str = "image/ktx2";

/// The format of a [`Texture`]'s texels.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
#[non_exhaustive]
pub enum Format {
    /// UASTC LDR 4×4, to be transcoded before it is sampled
    /// ([`crate::uastc`]). The channels say what the blocks hold, to help
    /// pick a transcode target.
    Uastc(UastcChannels),
    /// BC7: 4×4 blocks of 16 bytes.
    Bc7,
    /// ASTC LDR 4×4: 4×4 blocks of 16 bytes.
    Astc4x4,
    /// RGBA, 8 bits a channel, 4 bytes a texel (`VK_FORMAT_R8G8B8A8_*`).
    Rgba8,
}

/// What a UASTC texture's blocks hold: the channel id of its descriptor's
/// sample (KTX 2.0 §3.10.3, Khronos Data Format 1.4 §5.6.14).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum UastcChannels {
    /// Opaque colour (`KHR_DF_CHANNEL_UASTC_RGB`).
    Rgb,
    /// Colour and alpha (`KHR_DF_CHANNEL_UASTC_RGBA`).
    Rgba,
    /// One channel, R replicated in G and B (`KHR_DF_CHANNEL_UASTC_RRR`).
    Rrr,
    /// Two channels, R replicated in G and B and G in alpha
    /// (`KHR_DF_CHANNEL_UASTC_RRRG`).
    Rrrg,
    /// Two channels, R and G (`KHR_DF_CHANNEL_UASTC_RG`).
    Rg,
}

/// How a file's levels are stored (KTX 2.0 §3.8). Each level is compressed
/// on its own.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash)]
#[non_exhaustive]
pub enum Supercompression {
    /// As they are (scheme 0).
    #[default]
    None,
    /// Zstandard (scheme 2). Written at the fastest level of the pure-Rust
    /// encoder; any Zstandard stream is read.
    Zstd,
    /// ZLIB (scheme 3, RFC 1950), written at level 9.
    Zlib,
}

/// One texture as a KTX 2.0 file holds it: its format, its shape and its
/// levels.
///
/// A level holds every image of its mip level, in the file's order (§3.13):
/// for each array layer (one if not an array), for each face (one, or six
/// for a cubemap: +X, -X, +Y, -Y, +Z, -Z), for each depth slice of a 3D
/// texture (one otherwise), the image's rows top to bottom; a row of a block
/// format is a row of 4×4 blocks of 16 bytes, of RGBA8 its texels.
/// [`Texture::image`] cuts one image out of a level.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Texture {
    /// The texels' format.
    pub format: Format,
    /// Whether the texels are sRGB-encoded: the `*_SRGB*` `vkFormat` and the
    /// sRGB transfer function in the descriptor.
    pub srgb: bool,
    /// Width of level 0, in texels.
    pub width: u32,
    /// Height of level 0, in texels; 0 for a 1D texture.
    pub height: u32,
    /// Depth of level 0 of a 3D texture, in texels; 0 for any other.
    pub depth: u32,
    /// Array layers; 0 for a texture that is not an array (§3.5).
    pub layers: u32,
    /// 1, or 6 for a cubemap (§3.6).
    pub faces: u32,
    /// The levels, level 0 first. Level `p` is `max(1, width >> p)` ×
    /// `max(1, height >> p)` × `max(1, depth >> p)` texels, each image of
    /// it in whole blocks.
    pub levels: Vec<Vec<u8>>,
    /// The file's `levelCount` is 0: it holds level 0 only, and the loader
    /// is to generate the mips (§3.7). RGBA8 only.
    pub generate_mips: bool,
    /// The colour channels are premultiplied by alpha (the descriptor's
    /// `KHR_DF_FLAG_ALPHA_PREMULTIPLIED`).
    pub premultiplied_alpha: bool,
    /// How the levels are stored in the file.
    pub supercompression: Supercompression,
    /// The key/value pairs other than `KTXorientation` and `KTXwriter`,
    /// which the writer writes itself: each key (UTF-8, no NUL) and its
    /// value as stored (a string value keeps its NUL). Written sorted.
    pub key_values: Vec<(String, Vec<u8>)>,
}

/// Why a file cannot be read, or a [`Texture`] written.
#[derive(Clone, Debug, PartialEq, Eq, thiserror::Error)]
#[non_exhaustive]
pub enum Ktx2Error {
    /// The file does not start with the KTX 2.0 identifier (§3.1).
    #[error("not a KTX 2.0 file: the identifier differs")]
    Identifier,
    /// A part of the file lies, at least partly, beyond its end.
    #[error(
        "{what} ({length} bytes at offset {offset}) lies beyond the file's end ({file} bytes)"
    )]
    OutOfBounds {
        /// The part of the file.
        what: &'static str,
        /// Its offset from the start of the file.
        offset: u64,
        /// Its length.
        length: u64,
        /// The file's length.
        file: usize,
    },
    /// A supercompression scheme this module does not read: 1 (BasisLZ,
    /// which only ETC1S uses) or one the specification does not define.
    #[error("supercompression scheme {0} is not supported, only 0 (none), 2 (Zstandard) and 3 (ZLIB)")]
    Supercompression(u32),
    /// A `vkFormat` other than those of [`Format`].
    #[error("vkFormat {0} is not supported (UNDEFINED with UASTC, BC7, ASTC 4x4 and R8G8B8A8 only)")]
    VkFormat(u32),
    /// A valid kind of texture this module does not read.
    #[error("not supported: {0}")]
    Unsupported(&'static str),
    /// The header or the index breaks a rule of the specification, or a
    /// texture to write has an impossible shape.
    #[error("invalid header: {0}")]
    Header(&'static str),
    /// The data format descriptor is invalid or does not match the format.
    #[error("invalid data format descriptor: {0}")]
    Dfd(&'static str),
    /// The key/value data is invalid.
    #[error("invalid key/value data: {0}")]
    KeyValue(&'static str),
    /// The file says its texels start other than at the top left
    /// (`KTXorientation`, §5.2): read as stored, the image would be flipped.
    #[error("orientation {0:?} is not supported, only \"r\", \"rd\" or \"rdi\" (from the top left)")]
    Orientation(String),
    /// A level's entry in the level index, its data, or a level to write, is
    /// invalid.
    #[error("level {level}: {reason}")]
    Level {
        /// The level, 0 being the largest.
        level: usize,
        /// What is wrong with it.
        reason: &'static str,
    },
}

impl Format {
    /// The `vkFormat` of a texture in this format (KTX 2.0 §3.2).
    pub const fn vk_format(self, srgb: bool) -> u32 {
        match (self, srgb) {
            (Format::Uastc(_), _) => VK_FORMAT_UNDEFINED,
            (Format::Bc7, false) => VK_FORMAT_BC7_UNORM_BLOCK,
            (Format::Bc7, true) => VK_FORMAT_BC7_SRGB_BLOCK,
            (Format::Astc4x4, false) => VK_FORMAT_ASTC_4X4_UNORM_BLOCK,
            (Format::Astc4x4, true) => VK_FORMAT_ASTC_4X4_SRGB_BLOCK,
            (Format::Rgba8, false) => VK_FORMAT_R8G8B8A8_UNORM,
            (Format::Rgba8, true) => VK_FORMAT_R8G8B8A8_SRGB,
        }
    }

    /// The block format the GPU samples, or `None` for UASTC, which is
    /// transcoded first, and for RGBA8.
    pub const fn block_format(self) -> Option<BlockFormat> {
        match self {
            Format::Bc7 => Some(BlockFormat::Bc7),
            Format::Astc4x4 => Some(BlockFormat::Astc4x4),
            Format::Uastc(_) | Format::Rgba8 => None,
        }
    }

    /// Side of a texel block, in texels: 4 for the block formats, 1 for
    /// RGBA8.
    pub const fn block_dim(self) -> u32 {
        match self {
            Format::Rgba8 => 1,
            _ => 4,
        }
    }

    /// Bytes per texel block: 16 for the block formats, 4 for RGBA8.
    pub const fn block_bytes(self) -> u32 {
        match self {
            Format::Rgba8 => 4,
            _ => 16,
        }
    }

    /// The descriptor's colour model (Khronos Data Format 1.4 §5.6).
    const fn color_model(self) -> u8 {
        match self {
            Format::Uastc(_) => KHR_DF_MODEL_UASTC,
            Format::Bc7 => KHR_DF_MODEL_BC7,
            Format::Astc4x4 => KHR_DF_MODEL_ASTC,
            Format::Rgba8 => KHR_DF_MODEL_RGBSDA,
        }
    }
}

impl From<BlockFormat> for Format {
    fn from(f: BlockFormat) -> Self {
        match f {
            BlockFormat::Bc7 => Format::Bc7,
            BlockFormat::Astc4x4 => Format::Astc4x4,
        }
    }
}

impl UastcChannels {
    /// The channel id (Khronos Data Format 1.4, table 73).
    pub const fn channel_id(self) -> u8 {
        match self {
            UastcChannels::Rgb => 0,
            UastcChannels::Rgba => 3,
            UastcChannels::Rrr => 4,
            UastcChannels::Rrrg => 5,
            UastcChannels::Rg => 6,
        }
    }

    /// The channels of a channel id, if it is one of table 73's.
    pub const fn from_channel_id(id: u8) -> Option<Self> {
        Some(match id {
            0 => UastcChannels::Rgb,
            3 => UastcChannels::Rgba,
            4 => UastcChannels::Rrr,
            5 => UastcChannels::Rrrg,
            6 => UastcChannels::Rg,
            _ => return None,
        })
    }
}

impl Texture {
    /// A 2D texture, not an array, not a cubemap, stored as it is, with no
    /// key/value pair of its own.
    pub fn new(format: Format, srgb: bool, width: u32, height: u32, levels: Vec<Vec<u8>>) -> Self {
        Self {
            format,
            srgb,
            width,
            height,
            depth: 0,
            layers: 0,
            faces: 1,
            levels,
            generate_mips: false,
            premultiplied_alpha: false,
            supercompression: Supercompression::None,
            key_values: Vec::new(),
        }
    }

    /// The number of levels of the full chain of a texture of these
    /// dimensions, down to 1×1×1: `floor(log2(max(width, height, depth))) +
    /// 1` (§3.7).
    pub const fn full_chain_3d(width: u32, height: u32, depth: u32) -> usize {
        let mut side = if width > height { width } else { height };
        if depth > side {
            side = depth;
        }
        if side == 0 {
            0
        } else {
            (u32::BITS - side.leading_zeros()) as usize
        }
    }

    /// The number of levels of the full chain of a `width`×`height`
    /// texture, down to 1×1 (§3.7).
    pub const fn full_chain(width: u32, height: u32) -> usize {
        Self::full_chain_3d(width, height, 0)
    }

    /// Images in each level: layers × faces (§3.13).
    pub fn images_per_level(&self) -> u64 {
        self.layers.max(1) as u64 * self.faces as u64
    }

    /// The size of level `level` in texels: width, height, depth, each at
    /// least 1.
    pub fn level_size(&self, level: usize) -> Option<(u32, u32, u32)> {
        let shift = u32::try_from(level).ok().filter(|&s| s < u32::BITS)?;
        Some((
            (self.width >> shift).max(1),
            (self.height >> shift).max(1),
            (self.depth >> shift).max(1),
        ))
    }

    /// The bytes of one image (one layer, one face, one depth slice) of
    /// level `level`, in whole blocks, or `None` when that overflows.
    pub fn image_bytes(&self, level: usize) -> Option<u64> {
        let (w, h, _) = self.level_size(level)?;
        let dim = self.format.block_dim();
        (w.div_ceil(dim) as u64)
            .checked_mul(h.div_ceil(dim) as u64)?
            .checked_mul(self.format.block_bytes() as u64)
    }

    /// The bytes level `level` takes: every image of it, every depth slice
    /// (§3.13), or `None` when that overflows.
    pub fn level_bytes(&self, level: usize) -> Option<u64> {
        let (_, _, d) = self.level_size(level)?;
        self.image_bytes(level)?
            .checked_mul(d as u64)?
            .checked_mul(self.images_per_level())
    }

    /// One image of level `level`: array layer `layer` (0 if not an array),
    /// face `face` (0 if not a cubemap), depth slice `slice` (0 if not 3D).
    pub fn image(&self, level: usize, layer: u32, face: u32, slice: u32) -> Option<&[u8]> {
        let (_, _, d) = self.level_size(level)?;
        if layer >= self.layers.max(1) || face >= self.faces || slice >= d {
            return None;
        }
        let n = self.image_bytes(level)? as usize;
        let at = ((layer as usize * self.faces as usize + face as usize) * d as usize
            + slice as usize)
            * n;
        self.levels.get(level)?.get(at..at + n)
    }

    /// Checks what [`write()`] checks: a type KTX 2.0 defines (§4.1) in a
    /// shape its format can hold, between 1 and the full chain's number of
    /// levels (1 with [`Texture::generate_mips`]), each the length of its
    /// images, and key/value pairs that can be written.
    pub fn validate(&self) -> Result<(), Ktx2Error> {
        if self.width == 0 {
            return Err(Ktx2Error::Header("pixelWidth must not be 0"));
        }
        check_shape(
            self.format,
            self.height,
            self.depth,
            self.layers,
            self.faces,
            self.width,
        )?;
        if self.levels.is_empty() {
            return Err(Ktx2Error::Header("a texture needs at least one level"));
        }
        if self.levels.len() > Self::full_chain_3d(self.width, self.height, self.depth) {
            return Err(Ktx2Error::Header(
                "more levels than the texture's size allows",
            ));
        }
        if self.generate_mips {
            if self.format != Format::Rgba8 {
                return Err(Ktx2Error::Header(
                    "levelCount 0 (mips to generate) is not allowed for block-compressed formats",
                ));
            }
            if self.levels.len() != 1 {
                return Err(Ktx2Error::Header(
                    "a texture whose mips are to be generated holds level 0 alone",
                ));
            }
        }
        for (level, bytes) in self.levels.iter().enumerate() {
            if self.level_bytes(level) != Some(bytes.len() as u64) {
                return Err(Ktx2Error::Level {
                    level,
                    reason: "its length is not its images' size in whole texel blocks",
                });
            }
        }
        for (i, (key, _)) in self.key_values.iter().enumerate() {
            if key.is_empty() || key.contains('\0') {
                return Err(Ktx2Error::KeyValue("a key is empty or holds a NUL"));
            }
            if key == "KTXorientation" || key == "KTXwriter" {
                return Err(Ktx2Error::KeyValue(
                    "KTXorientation and KTXwriter are written by the writer",
                ));
            }
            if self.key_values[..i].iter().any(|(k, _)| k == key) {
                return Err(Ktx2Error::KeyValue("a key repeats"));
            }
        }
        Ok(())
    }
}

/// The texture types of §4.1 and what each format can be: `height` 0 is 1D,
/// `depth` above 0 is 3D, `faces` 6 a cubemap.
fn check_shape(
    format: Format,
    height: u32,
    depth: u32,
    layers: u32,
    faces: u32,
    width: u32,
) -> Result<(), Ktx2Error> {
    match faces {
        1 => {}
        6 => {
            if depth != 0 || width != height {
                return Err(Ktx2Error::Header(
                    "a cubemap is 2D with square faces (§4.1)",
                ));
            }
        }
        _ => return Err(Ktx2Error::Header("faceCount must be 1 or 6")),
    }
    if height == 0 && depth != 0 {
        return Err(Ktx2Error::Header(
            "pixelHeight 0 (1D) with a depth is not a texture type",
        ));
    }
    if depth != 0 && layers != 0 {
        return Err(Ktx2Error::Unsupported(
            "3D array textures (KTX 2.0 does not define them)",
        ));
    }
    if format != Format::Rgba8 && height == 0 {
        return Err(Ktx2Error::Header(
            "pixelHeight must not be 0 for a block-compressed format",
        ));
    }
    Ok(())
}

// vkFormat values (Vulkan's `VkFormat`; KTX 2.0 §3.2).
const VK_FORMAT_UNDEFINED: u32 = 0;
const VK_FORMAT_R8G8B8A8_UNORM: u32 = 37;
const VK_FORMAT_R8G8B8A8_SRGB: u32 = 43;
const VK_FORMAT_BC7_UNORM_BLOCK: u32 = 145;
const VK_FORMAT_BC7_SRGB_BLOCK: u32 = 146;
const VK_FORMAT_ASTC_4X4_UNORM_BLOCK: u32 = 157;
const VK_FORMAT_ASTC_4X4_SRGB_BLOCK: u32 = 158;

// Supercompression schemes (KTX 2.0 §3.8). Scheme 1, BasisLZ, is not read.
const SCHEME_NONE: u32 = 0;
const SCHEME_ZSTD: u32 = 2;
const SCHEME_ZLIB: u32 = 3;

// Khronos Data Format 1.4: colour models (§5.6), primaries (§5.7), transfer
// functions (§5.8), flags (§5.9), channels (§5.6.1) and sample qualifiers
// (§5.12).
const KHR_DF_MODEL_RGBSDA: u8 = 1;
const KHR_DF_MODEL_BC7: u8 = 134;
const KHR_DF_MODEL_ASTC: u8 = 162;
const KHR_DF_MODEL_ETC1S: u8 = 163;
const KHR_DF_MODEL_UASTC: u8 = 166;
const KHR_DF_PRIMARIES_BT709: u8 = 1;
const KHR_DF_TRANSFER_LINEAR: u8 = 1;
const KHR_DF_TRANSFER_SRGB: u8 = 2;
const KHR_DF_FLAG_ALPHA_PREMULTIPLIED: u8 = 1;
const KHR_DF_CHANNEL_RGBSDA_ALPHA: u8 = 15;
/// The `F` qualifier: float data.
const KHR_DF_SAMPLE_DATATYPE_FLOAT: u8 = 0x80;
/// The `L` qualifier: a linear channel in an sRGB texture (its alpha).
const KHR_DF_SAMPLE_DATATYPE_LINEAR: u8 = 0x10;
/// The Basic Data Format Descriptor Block's version (§5.3).
const KHR_DF_VERSIONNUMBER: u32 = 2;

/// The identifier every KTX 2.0 file starts with (§3.1).
const IDENTIFIER: [u8; 12] = [
    0xAB, 0x4B, 0x54, 0x58, 0x20, 0x32, 0x30, 0xBB, 0x0D, 0x0A, 0x1A, 0x0A,
];
/// The identifier, the header (§3.2–3.8) and the index (§3.9), before the
/// level index (§3.9.7).
const HEADER_BYTES: usize = 80;
/// One level index entry: byteOffset, byteLength, uncompressedByteLength.
const LEVEL_ENTRY_BYTES: usize = 24;
const KEY_ORIENTATION: &str = "KTXorientation";
const KEY_WRITER: &str = "KTXwriter";
const WRITER: &str = concat!("texcomp ", env!("CARGO_PKG_VERSION"));
/// The most a file's levels may decompress to: a hostile header cannot make
/// the reader allocate more.
const MAX_DECOMPRESSED: u64 = 1 << 30;

/// The orientation written and accepted, by dimension count: texels from
/// the top left, S to the right, T downwards, R into the screen (§5.2).
fn orientation(height: u32, depth: u32) -> &'static str {
    if height == 0 {
        "r"
    } else if depth == 0 {
        "rd"
    } else {
        "rdi"
    }
}

/// The level alignment without supercompression: lcm(texel block size, 4)
/// (§3.13.2). 16 for the block formats, 4 for RGBA8. With supercompression,
/// 1.
fn level_align(format: Format, scheme: u32) -> u64 {
    if scheme != SCHEME_NONE {
        1
    } else {
        match format {
            Format::Rgba8 => 4,
            _ => 16,
        }
    }
}

/// Writes `texture` as a KTX 2.0 file.
///
/// The file holds, in this order (§2): the header and index; the level
/// index; a data format descriptor with one basic block; the key/value data,
/// sorted by key: `KTXorientation` (`r`, `rd` or `rdi` by dimension count),
/// `KTXwriter` and the texture's own pairs; then the levels, smallest first,
/// each aligned (§3.13.2) and supercompressed as the texture says.
///
/// Fails, writing nothing, when [`Texture::validate`] does.
pub fn write(texture: &Texture) -> Result<Vec<u8>, Ktx2Error> {
    texture.validate()?;
    let scheme = match texture.supercompression {
        Supercompression::None => SCHEME_NONE,
        Supercompression::Zstd => SCHEME_ZSTD,
        Supercompression::Zlib => SCHEME_ZLIB,
    };
    let stored: Vec<Vec<u8>> = texture
        .levels
        .iter()
        .map(|level| match texture.supercompression {
            Supercompression::None => level.clone(),
            Supercompression::Zstd => {
                ruzstd::encoding::compress_to_vec(&level[..], ruzstd::encoding::CompressionLevel::Fastest)
            }
            Supercompression::Zlib => miniz_oxide::deflate::compress_to_vec_zlib(level, 9),
        })
        .collect();
    let n = stored.len();
    let dfd = dfd(texture);
    let dfd_offset = HEADER_BYTES + LEVEL_ENTRY_BYTES * n;
    let kvd_offset = dfd_offset + dfd.len();
    let mut pairs: Vec<(&str, Vec<u8>)> = vec![
        (
            KEY_ORIENTATION,
            [orientation(texture.height, texture.depth).as_bytes(), b"\0"].concat(),
        ),
        (KEY_WRITER, [WRITER.as_bytes(), b"\0"].concat()),
    ];
    pairs.extend(
        texture
            .key_values
            .iter()
            .map(|(k, v)| (k.as_str(), v.clone())),
    );
    pairs.sort_by(|a, b| a.0.as_bytes().cmp(b.0.as_bytes()));
    let kvd = key_value_data(&pairs);
    let align = level_align(texture.format, scheme);
    let data_offset = (kvd_offset + kvd.len()).next_multiple_of(align as usize);

    let mut f = Vec::with_capacity(data_offset + stored.iter().map(Vec::len).sum::<usize>());
    // §3.1–3.8.
    f.extend_from_slice(&IDENTIFIER);
    for v in [
        texture.format.vk_format(texture.srgb),
        1, // typeSize: 1 for these formats (§3.3).
        texture.width,
        texture.height,
        texture.depth,
        texture.layers,
        texture.faces,
        if texture.generate_mips { 0 } else { n as u32 },
        scheme,
    ] {
        f.extend_from_slice(&v.to_le_bytes());
    }
    // §3.9: the index. No scheme written has global data (§3.9.5, §3.9.6).
    for v in [dfd_offset, dfd.len(), kvd_offset, kvd.len()] {
        f.extend_from_slice(&(v as u32).to_le_bytes());
    }
    f.extend_from_slice(&[0; 16]);
    // §3.9.7: the level index, level 0 first, while the levels themselves
    // are stored smallest first (§3.13), each aligned.
    let mut offset = data_offset as u64;
    let mut offsets = vec![0; n];
    for p in (0..n).rev() {
        offset = offset.next_multiple_of(align);
        offsets[p] = offset;
        offset += stored[p].len() as u64;
    }
    for p in 0..n {
        for v in [
            offsets[p],
            stored[p].len() as u64,
            texture.levels[p].len() as u64,
        ] {
            f.extend_from_slice(&v.to_le_bytes());
        }
    }
    // §3.10, §3.11.
    f.extend_from_slice(&dfd);
    f.extend_from_slice(&kvd);
    // §3.13: mipPadding before each level.
    for p in (0..n).rev() {
        f.resize(offsets[p] as usize, 0);
        f.extend_from_slice(&stored[p]);
    }
    Ok(f)
}

/// The data format descriptor: `dfdTotalSize` and one Basic Data Format
/// Descriptor Block (KTX 2.0 §3.10, Khronos Data Format 1.4 §5, the 4×4
/// examples of §5.6.7, §5.6.10 and §5.6.14, and for RGBA8 the R8G8B8A8
/// descriptor of §5.6.1).
fn dfd(texture: &Texture) -> Vec<u8> {
    let format = texture.format;
    let samples: Vec<[u8; 16]> = match format {
        Format::Rgba8 => (0..4u8)
            .map(|c| {
                let mut s = [0u8; 16];
                let channel = if c == 3 { KHR_DF_CHANNEL_RGBSDA_ALPHA } else { c };
                // Alpha is linear in an sRGB texture.
                let qualifiers = if c == 3 && texture.srgb {
                    KHR_DF_SAMPLE_DATATYPE_LINEAR
                } else {
                    0
                };
                s[0..2].copy_from_slice(&(8 * c as u16).to_le_bytes());
                s[2] = 7;
                s[3] = channel | qualifiers;
                s[12..16].copy_from_slice(&255u32.to_le_bytes());
                s
            })
            .collect(),
        _ => {
            // bitOffset 0, bitLength 128 stored as 127, the channel id with
            // no qualifier, sampleLower 0, sampleUpper UINT32_MAX.
            let mut s = [0u8; 16];
            s[2] = 127;
            s[3] = match format {
                Format::Uastc(c) => c.channel_id(),
                _ => 0,
            };
            s[12..16].copy_from_slice(&u32::MAX.to_le_bytes());
            vec![s]
        }
    };
    let block_size = 24 + 16 * samples.len();
    let mut d = Vec::with_capacity(4 + block_size);
    d.extend_from_slice(&((4 + block_size) as u32).to_le_bytes());
    // Word 0: vendorId 0 (Khronos) and descriptorType 0 (basic), §5.1–5.2.
    d.extend_from_slice(&0u32.to_le_bytes());
    // Word 1: versionNumber, then descriptorBlockSize (§5.3–5.4).
    d.extend_from_slice(&(KHR_DF_VERSIONNUMBER | (block_size as u32) << 16).to_le_bytes());
    // Word 2: colorModel, colorPrimaries, transferFunction, flags. The sRGB
    // transfer is required with an *_SRGB vkFormat (KTX 2.0 §3.10.1).
    let transfer = if texture.srgb {
        KHR_DF_TRANSFER_SRGB
    } else {
        KHR_DF_TRANSFER_LINEAR
    };
    let flags = if texture.premultiplied_alpha {
        KHR_DF_FLAG_ALPHA_PREMULTIPLIED
    } else {
        0
    };
    d.extend_from_slice(&[format.color_model(), KHR_DF_PRIMARIES_BT709, transfer, flags]);
    // Word 3: texelBlockDimension0..3, each the size minus one.
    let dim = (format.block_dim() - 1) as u8;
    d.extend_from_slice(&[dim, dim, 0, 0]);
    // Words 4–5: bytesPlane0..7: one plane.
    d.extend_from_slice(&[format.block_bytes() as u8, 0, 0, 0, 0, 0, 0, 0]);
    for s in samples {
        d.extend_from_slice(&s);
    }
    d
}

/// Key/value data (§3.11): each pair is its length, the key, a NUL, the
/// value, then padding to 4 bytes. The pairs are sorted by key.
fn key_value_data(pairs: &[(&str, Vec<u8>)]) -> Vec<u8> {
    let mut out = Vec::new();
    for (key, value) in pairs {
        let len = key.len() + 1 + value.len();
        out.extend_from_slice(&(len as u32).to_le_bytes());
        out.extend_from_slice(key.as_bytes());
        out.push(0);
        out.extend_from_slice(value);
        out.resize(out.len().next_multiple_of(4), 0);
    }
    out
}

/// Reads a KTX 2.0 file.
///
/// Checks the identifier; the header against the texture types of §4.1 and
/// the formats read here; the descriptor against `vkFormat`, sample by
/// sample; the key/value data's structure and order, and its orientation;
/// that every level lies inside the file, aligned, smallest first, after
/// the metadata; and that each level, decompressed, is exactly its images'
/// size.
///
/// Never panics: any bytes give a texture or an error.
pub fn read(bytes: &[u8]) -> Result<Texture, Ktx2Error> {
    if bytes.get(..IDENTIFIER.len()) != Some(&IDENTIFIER[..]) {
        return Err(Ktx2Error::Identifier);
    }
    let file = Reader(bytes);
    let header = file.section("the header and index", 0, HEADER_BYTES as u64)?;
    let word = |i: usize| u32_le(header, 12 + 4 * i);
    let [vk_format, type_size, width, height, depth, layers, faces, level_count, scheme] =
        [0, 1, 2, 3, 4, 5, 6, 7, 8].map(word);
    // §3.8. Checked first, so a file in a scheme not read says so.
    let supercompression = match scheme {
        SCHEME_NONE => Supercompression::None,
        SCHEME_ZSTD => Supercompression::Zstd,
        SCHEME_ZLIB => Supercompression::Zlib,
        other => return Err(Ktx2Error::Supercompression(other)),
    };
    let (format_kind, srgb_from_vk) = match vk_format {
        VK_FORMAT_UNDEFINED => (None, None),
        VK_FORMAT_R8G8B8A8_UNORM => (Some(Format::Rgba8), Some(false)),
        VK_FORMAT_R8G8B8A8_SRGB => (Some(Format::Rgba8), Some(true)),
        VK_FORMAT_BC7_UNORM_BLOCK => (Some(Format::Bc7), Some(false)),
        VK_FORMAT_BC7_SRGB_BLOCK => (Some(Format::Bc7), Some(true)),
        VK_FORMAT_ASTC_4X4_UNORM_BLOCK => (Some(Format::Astc4x4), Some(false)),
        VK_FORMAT_ASTC_4X4_SRGB_BLOCK => (Some(Format::Astc4x4), Some(true)),
        other => return Err(Ktx2Error::VkFormat(other)),
    };
    // §3.3.
    if type_size != 1 {
        return Err(Ktx2Error::Header("typeSize must be 1 for these formats"));
    }
    if width == 0 {
        return Err(Ktx2Error::Header("pixelWidth must not be 0"));
    }
    // The texture types of §4.1, against the format UNDEFINED stands for
    // (UASTC, a block format); refined once the descriptor is read.
    check_shape(
        format_kind.unwrap_or(Format::Bc7),
        height,
        depth,
        layers,
        faces,
        width,
    )?;
    // §3.7: 0 means one level stored and the rest to generate, which a
    // block-compressed format does not allow. The chain stops at 1×1×1,
    // which also bounds the level index to 32 entries.
    let generate_mips = level_count == 0;
    if generate_mips && format_kind != Some(Format::Rgba8) {
        return Err(Ktx2Error::Header(
            "levelCount 0 is not allowed for block-compressed formats",
        ));
    }
    let n = level_count.max(1) as usize;
    if n > Texture::full_chain_3d(width, height, depth) {
        return Err(Ktx2Error::Header(
            "levelCount exceeds the levels the texture's size allows",
        ));
    }

    // §3.9: the index.
    let dfd_offset = u32_le(header, 48) as u64;
    let dfd_length = u32_le(header, 52) as u64;
    let kvd_offset = u32_le(header, 56) as u64;
    let kvd_length = u32_le(header, 60) as u64;
    let sgd_offset = u64_le(header, 64);
    let sgd_length = u64_le(header, 72);
    // §3.9.6: only BasisLZ has global data.
    if sgd_length != 0 || sgd_offset != 0 {
        return Err(Ktx2Error::Header(
            "sgdByteOffset and sgdByteLength must be 0 without BasisLZ",
        ));
    }
    let level_index = file.section(
        "the level index",
        HEADER_BYTES as u64,
        (LEVEL_ENTRY_BYTES * n) as u64,
    )?;

    // §3.10.
    let dfd = file.section("the data format descriptor", dfd_offset, dfd_length)?;
    if kvd_length != 0 && kvd_offset.checked_sub(dfd_offset) != Some(dfd_length) {
        return Err(Ktx2Error::Dfd(
            "dfdTotalSize must equal kvdByteOffset - dfdByteOffset",
        ));
    }
    let described = read_dfd(dfd, format_kind, srgb_from_vk)?;
    let format = described.format;

    // §3.11.
    let key_values = if kvd_length != 0 {
        let kvd = file.section("the key/value data", kvd_offset, kvd_length)?;
        read_key_values(kvd, orientation(height, depth))?
    } else {
        Vec::new()
    };
    let metadata_end = [
        HEADER_BYTES as u64 + level_index.len() as u64,
        dfd_offset + dfd_length,
        if kvd_length != 0 {
            kvd_offset + kvd_length
        } else {
            0
        },
    ]
    .into_iter()
    .max()
    .unwrap_or(0);

    let mut texture = Texture {
        format,
        srgb: described.srgb,
        width,
        height,
        depth,
        layers,
        faces,
        levels: Vec::with_capacity(n),
        generate_mips,
        premultiplied_alpha: described.premultiplied,
        supercompression,
        key_values,
    };

    // §3.9.7 and §3.13: the levels.
    let align = level_align(format, scheme);
    let mut next_start = None::<u64>;
    let mut decompressed = 0u64;
    for p in 0..n {
        let e = &level_index[LEVEL_ENTRY_BYTES * p..LEVEL_ENTRY_BYTES * (p + 1)];
        let (offset, length, uncompressed) = (u64_le(e, 0), u64_le(e, 8), u64_le(e, 16));
        let bad = |reason| Err(Ktx2Error::Level { level: p, reason });
        if texture.level_bytes(p) != Some(uncompressed) {
            return bad("uncompressedByteLength is not the level's images' size in whole texel blocks");
        }
        if scheme == SCHEME_NONE && length != uncompressed {
            return bad("byteLength must equal uncompressedByteLength without supercompression");
        }
        if !offset.is_multiple_of(align) {
            return bad("byteOffset is not aligned (mipPadding)");
        }
        if offset < metadata_end {
            return bad("the level overlaps the header, index or metadata");
        }
        let data = file.section("a level's data", offset, length)?;
        // Smallest first: a level ends at or before the larger one's start.
        if let Some(start) = next_start {
            if offset + length > start {
                return bad("the level overlaps or follows the larger level");
            }
        }
        next_start = Some(offset);
        decompressed = decompressed.saturating_add(uncompressed);
        if scheme != SCHEME_NONE && decompressed > MAX_DECOMPRESSED {
            return bad("the levels decompress to more than the reader's limit of 1 GiB");
        }
        texture.levels.push(match supercompression {
            Supercompression::None => data.to_vec(),
            Supercompression::Zstd => {
                let mut out = vec![0u8; uncompressed as usize];
                let mut decoder = ruzstd::decoding::FrameDecoder::new();
                match decoder.decode_all(data, &mut out) {
                    Ok(written) if written as u64 == uncompressed => out,
                    _ => return bad("the Zstandard data does not decompress to uncompressedByteLength"),
                }
            }
            Supercompression::Zlib => {
                match miniz_oxide::inflate::decompress_to_vec_zlib_with_limit(
                    data,
                    uncompressed as usize,
                ) {
                    Ok(out) if out.len() as u64 == uncompressed => out,
                    _ => return bad("the ZLIB data does not decompress to uncompressedByteLength"),
                }
            }
        });
    }
    Ok(texture)
}

/// What the descriptor says beyond `vkFormat`.
struct Described {
    format: Format,
    srgb: bool,
    premultiplied: bool,
}

/// Reads the descriptor's basic block and checks it against `vkFormat`:
/// `kind` is the format `vkFormat` names (`None`: UNDEFINED) and `srgb` its
/// transfer (`None`: the descriptor says).
fn read_dfd(dfd: &[u8], kind: Option<Format>, srgb: Option<bool>) -> Result<Described, Ktx2Error> {
    // §3.10.4: dfdTotalSize, which must equal dfdByteLength.
    if dfd.len() < 4 + 24 + 16 {
        return Err(Ktx2Error::Dfd(
            "too short for a basic block with one sample",
        ));
    }
    if u32_le(dfd, 0) as usize != dfd.len() {
        return Err(Ktx2Error::Dfd("dfdTotalSize must equal dfdByteLength"));
    }
    let b = &dfd[4..];
    // Khronos Data Format 1.4 §5.1–5.4. The first block must be the basic
    // one; any block after it is not needed here.
    let w0 = u32_le(b, 0);
    if w0 & 0x1_ffff != 0 || w0 >> 17 != 0 {
        return Err(Ktx2Error::Dfd(
            "the first block is not a Khronos basic descriptor block",
        ));
    }
    let w1 = u32_le(b, 4);
    if w1 & 0xffff != KHR_DF_VERSIONNUMBER {
        return Err(Ktx2Error::Dfd("the basic block's versionNumber is not 2"));
    }
    let block_size = (w1 >> 16) as usize;
    if block_size < 24 + 16 || !(block_size - 24).is_multiple_of(16) || block_size > b.len() {
        return Err(Ktx2Error::Dfd(
            "descriptorBlockSize is not 24 + 16 per sample within the DFD",
        ));
    }
    let samples = (block_size - 24) / 16;
    let sample = |i: usize| &b[24 + 16 * i..24 + 16 * (i + 1)];
    // §5.5–5.9.
    let (model, transfer, flags) = (b[8], b[10], b[11]);
    if model == KHR_DF_MODEL_ETC1S {
        return Err(Ktx2Error::Unsupported("ETC1S (BasisLZ) textures"));
    }
    let premultiplied = flags & KHR_DF_FLAG_ALPHA_PREMULTIPLIED != 0;
    let srgb_transfer = match transfer {
        KHR_DF_TRANSFER_SRGB => true,
        KHR_DF_TRANSFER_LINEAR => false,
        _ => return Err(Ktx2Error::Dfd("transfer function neither linear nor sRGB")),
    };
    let format = match kind {
        None => {
            // KTX 2.0 §3.10.3: UNDEFINED with the UASTC model, one sample
            // whose channel id says the channels, no float qualifier.
            if model != KHR_DF_MODEL_UASTC {
                return Err(Ktx2Error::Dfd(
                    "vkFormat UNDEFINED with a colour model other than UASTC",
                ));
            }
            if samples != 1 {
                return Err(Ktx2Error::Dfd("a UASTC descriptor has one sample"));
            }
            let channel = sample(0)[3];
            if channel & KHR_DF_SAMPLE_DATATYPE_FLOAT != 0 {
                return Err(Ktx2Error::Dfd(
                    "UASTC is LDR: the float qualifier must be clear",
                ));
            }
            Format::Uastc(
                UastcChannels::from_channel_id(channel & 0x0f)
                    .ok_or(Ktx2Error::Dfd("not a UASTC channel id"))?,
            )
        }
        Some(format) => {
            // KTX 2.0 §3.10.1: the model and the sizes match the format.
            if model != format.color_model() {
                return Err(Ktx2Error::Dfd("the colour model does not match vkFormat"));
            }
            format
        }
    };
    // KTX 2.0 §3.10.1: an *_SRGB vkFormat has the sRGB transfer, a UNORM one
    // does not.
    if let Some(srgb) = srgb {
        if srgb != srgb_transfer {
            return Err(Ktx2Error::Dfd(
                "the transfer function does not match the vkFormat's sRGB-ness",
            ));
        }
    }
    // §5.10–5.11: the texel block and its one plane.
    let dim = (format.block_dim() - 1) as u8;
    if b[12..16] != [dim, dim, 0, 0] {
        return Err(Ktx2Error::Dfd("texelBlockDimension does not match the format"));
    }
    if b[16..24] != [format.block_bytes() as u8, 0, 0, 0, 0, 0, 0, 0] {
        return Err(Ktx2Error::Dfd("bytesPlane does not match the format"));
    }
    // §5.12–5.17: the samples.
    match format {
        Format::Rgba8 => {
            if samples != 4 {
                return Err(Ktx2Error::Dfd("an R8G8B8A8 descriptor has four samples"));
            }
            for c in 0..4u8 {
                let s = sample(c as usize);
                let channel = if c == 3 { KHR_DF_CHANNEL_RGBSDA_ALPHA } else { c };
                let qualifiers = s[3] & 0xf0;
                let allowed = if c == 3 && srgb_transfer {
                    KHR_DF_SAMPLE_DATATYPE_LINEAR
                } else {
                    0
                };
                if u16::from_le_bytes([s[0], s[1]]) != 8 * c as u16
                    || s[2] != 7
                    || s[3] & 0x0f != channel
                    || qualifiers & !allowed != 0
                    || u32_le(s, 8) != 0
                    || u32_le(s, 12) != 255
                {
                    return Err(Ktx2Error::Dfd(
                        "the samples are not R, G, B, A of 8 bits in that order",
                    ));
                }
            }
        }
        _ => {
            let s = sample(0);
            if u16::from_le_bytes([s[0], s[1]]) != 0 || s[2] != 127 {
                return Err(Ktx2Error::Dfd(
                    "the sample does not cover the 128-bit block",
                ));
            }
        }
    }
    Ok(Described {
        format,
        srgb: srgb_transfer,
        premultiplied,
    })
}

/// Walks the key/value data (§3.11): every pair within it, at least a
/// one-byte key and its NUL, UTF-8 keys sorted and unique, the padding
/// accounted for to the byte. Checks `KTXorientation` (§5.2) against the
/// one texels from the top left have, `expected`; returns the other pairs
/// but `KTXwriter`.
fn read_key_values(kvd: &[u8], expected: &str) -> Result<Vec<(String, Vec<u8>)>, Ktx2Error> {
    let mut at = 0usize;
    let mut previous: Option<&[u8]> = None;
    let mut out = Vec::new();
    while at < kvd.len() {
        let len = kvd
            .get(at..at + 4)
            .map(|b| u32_le(b, 0) as usize)
            .ok_or(Ktx2Error::KeyValue(
                "a pair's length runs past kvdByteLength",
            ))?;
        if len < 2 {
            return Err(Ktx2Error::KeyValue(
                "keyAndValueByteLength must be at least 2",
            ));
        }
        let pair = (at + 4)
            .checked_add(len)
            .and_then(|end| kvd.get(at + 4..end))
            .ok_or(Ktx2Error::KeyValue("a pair runs past kvdByteLength"))?;
        let nul = pair
            .iter()
            .position(|&b| b == 0)
            .ok_or(Ktx2Error::KeyValue("a key has no NUL terminator"))?;
        let (key, value) = (&pair[..nul], &pair[nul + 1..]);
        let key_str = std::str::from_utf8(key)
            .ok()
            .filter(|k| !k.is_empty())
            .ok_or(Ktx2Error::KeyValue("a key is empty or not UTF-8"))?;
        // UTF-8's byte order is the code points' order.
        if previous.is_some_and(|p| p >= key) {
            return Err(Ktx2Error::KeyValue("keys are not sorted, or one repeats"));
        }
        previous = Some(key);
        if key_str == KEY_ORIENTATION {
            // The value is a string; readers must not rely on its NUL.
            let v = value.strip_suffix(b"\0").unwrap_or(value);
            if v != expected.as_bytes() {
                return Err(Ktx2Error::Orientation(
                    String::from_utf8_lossy(v).into_owned(),
                ));
            }
        } else if key_str != KEY_WRITER {
            out.push((key_str.to_owned(), value.to_vec()));
        }
        // valuePadding (§3.11.3).
        at = at + 4 + len.next_multiple_of(4);
    }
    if at != kvd.len() {
        return Err(Ktx2Error::KeyValue(
            "kvdByteLength is not the pairs and their padding",
        ));
    }
    Ok(out)
}

/// The file, read through bounds-checked sections.
struct Reader<'a>(&'a [u8]);

impl<'a> Reader<'a> {
    /// `length` bytes at `offset`, or why not.
    fn section(&self, what: &'static str, offset: u64, length: u64) -> Result<&'a [u8], Ktx2Error> {
        let out = || Ktx2Error::OutOfBounds {
            what,
            offset,
            length,
            file: self.0.len(),
        };
        let start = usize::try_from(offset).map_err(|_| out())?;
        let end = offset
            .checked_add(length)
            .and_then(|e| usize::try_from(e).ok())
            .ok_or_else(out)?;
        self.0.get(start..end).ok_or_else(out)
    }
}

/// A little-endian `u32` at `at`; the caller has checked the bounds.
fn u32_le(b: &[u8], at: usize) -> u32 {
    let mut w = [0; 4];
    w.copy_from_slice(&b[at..at + 4]);
    u32::from_le_bytes(w)
}

/// A little-endian `u64` at `at`; the caller has checked the bounds.
fn u64_le(b: &[u8], at: usize) -> u64 {
    let mut w = [0; 8];
    w.copy_from_slice(&b[at..at + 8]);
    u64::from_le_bytes(w)
}
